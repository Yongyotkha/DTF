function steps(names: string[], current: number, dates: Partial<Record<number, string>> = {}): RequestStep[] {
  return names.map((name, index) => ({
    name,
    state: index < current ? 'done' : index === current ? 'current' : 'todo',
    date: dates[index],
  }));
}

