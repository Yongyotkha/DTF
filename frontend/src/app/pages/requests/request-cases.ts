export function caseNumberLabel(item: Pick<ListedCase, 'code'>): string {
  return /^[A-Z]{2}\d{3,4}$/u.test(item.code) ? item.code : '—';
}

export function caseBrief(item: ListedCase): string {
  const kind = item.kind;
  const goods = item.goods.trim();
  const withGoods = (ask: string) => (goods && !ask.includes(goods) ? `${ask} ${goods}` : ask);
  if (/ปร\.?\s*8/u.test(kind)) return 'ขอคืนอากรที่ถูกเรียกเก็บจากการขยายการเรียกเก็บอากร';
  if (/ปร\.?\s*5/u.test(kind)) return 'ขอคืนอากรตอบโต้ที่ชำระไว้';
  if (/ปร\.?\s*7/u.test(kind)) return 'ขอให้ยุติการขยายการเรียกเก็บอากร';
  if (/ปร\.?\s*4/u.test(kind)) return 'ผู้ส่งออกหรือผู้ผลิตรายใหม่ขอทบทวนอากร';
  if (/ปร\.?\s*2\s*ก/u.test(kind)) return 'ขอทบทวนความตกลงระงับการทุ่มตลาดหรือการอุดหนุน';
  if (/ปร\.?\s*3\s*ก/u.test(kind)) return 'ขอให้ใช้ความตกลงระงับต่อไป';
  if (/ปร\.?\s*6/u.test(kind) || kind.includes('หลบเลี่ยง')) return withGoods('ขอให้ตรวจสอบการหลบเลี่ยงมาตรการ');
  if (/ปร\.?\s*3/u.test(kind) || kind.includes('มาตรา 57')) return withGoods('ขอให้เรียกเก็บอากรต่อไป');
  if (/ปร\.?\s*2/u.test(kind) || kind.includes('มาตรา 56')) return withGoods('ขอทบทวนอากรที่ใช้อยู่');
  if (kind.includes('ทบทวน') && (kind.includes('ปกป้อง') || item.measure.startsWith('SG'))) return withGoods('ขอทบทวนมาตรการปกป้อง');
  if (item.measure.startsWith('SG') || kind.includes('ปกป้อง')) return withGoods('ขอกำหนดมาตรการปกป้อง');
  if (kind.includes('ทบทวน')) return withGoods('ขอทบทวนมาตรการที่ใช้อยู่');
  return withGoods('ขอเปิดไต่สวน');
}

export function latestDate(item: ListedCase): string {
  for (let index = item.steps.length - 1; index >= 0; index -= 1) {
    const date = item.steps[index]?.date;
    if (date) return date;
  }
  return item.created || '—';
}

export function caseKey(item: ListedCase): string {
  const shared = archiveCases.some((other) => other.code === item.code && other.id !== item.id);
  return shared && /^[A-Za-z0-9]+$/u.test(item.id) ? item.id : item.code;
}

