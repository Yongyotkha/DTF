export function fillKnown(target: object, extra: Record<string, string> = readText): void {
  const bag = target as Record<string, unknown>;
  for (const [key, value] of Object.entries({ ...readParty, ...extra })) {
    if (Object.prototype.hasOwnProperty.call(bag, key) && (typeof bag[key] === 'string' || bag[key] === '')) bag[key] = value;
  }
}

