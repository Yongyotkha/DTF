export function measureOf(value: string): RequestMeasure {
  return requestMeasures.find((item) => item.value === value) ?? requestMeasures[0];
}

export function formOf(code: string): RequestForm | null {
  return requestForms.find((item) => item.code === code) ?? null;
}

export function purposeOf(form: RequestForm, measure: string): FormPurpose {
  return form.purposes[measure] ?? form.purposes[ad] ?? { label: form.label, summary: form.summary };
}

export function formsFor(measure: string): RequestForm[] {
  return requestForms.filter((item) => !!item.purposes[measure]);
}
